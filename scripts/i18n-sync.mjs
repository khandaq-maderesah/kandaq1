/**
 * Keeps the translation files consistent.
 *
 *   node scripts/i18n-sync.mjs          create missing namespace files + regenerate index files
 *   node scripts/i18n-sync.mjs --check  also report missing/extra keys and placeholder mismatches
 *                                       (exits 1 if any are found)
 *
 * Layout: src/i18n/messages/<locale>/<namespace>.json, English (en) is the source.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'src', 'i18n', 'messages')
const LOCALES = ['en', 'am', 'ar', 'om', 'so']
const check = process.argv.includes('--check')

const namespaces = readdirSync(join(dir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort()

for (const locale of LOCALES) {
  mkdirSync(join(dir, locale), { recursive: true })
  for (const ns of namespaces) {
    const file = join(dir, locale, `${ns}.json`)
    if (!existsSync(file)) writeFileSync(file, '{}\n')
  }
  const ident = (ns) => ns.replace(/[^a-zA-Z0-9_]/g, '_')
  const index =
    '// Generated by scripts/i18n-sync.mjs — do not edit by hand.\n' +
    namespaces.map((ns) => `import ${ident(ns)} from './${ns}.json'`).join('\n') +
    '\n\nconst messages = {\n' +
    namespaces.map((ns) => `  ${ns}: ${ident(ns)},`).join('\n') +
    '\n}\n\nexport default messages\n'
  writeFileSync(join(dir, locale, 'index.ts'), index)
}

if (check) {
  const flatten = (obj, prefix = '', out = {}) => {
    for (const [k, v] of Object.entries(obj)) {
      const key = prefix ? `${prefix}.${k}` : k
      if (v && typeof v === 'object') flatten(v, key, out)
      else out[key] = String(v)
    }
    return out
  }
  // Top-level ICU argument names, e.g. {count} or {name, select, ...}.
  const args = (msg) => {
    const names = new Set()
    let depth = 0
    for (let i = 0; i < msg.length; i++) {
      if (msg[i] === '{') {
        if (depth === 0) {
          const m = /^\{\s*([a-zA-Z0-9_]+)/.exec(msg.slice(i))
          if (m) names.add(m[1])
        }
        depth++
      } else if (msg[i] === '}') depth--
    }
    return [...names].sort().join(',')
  }
  let problems = 0
  for (const ns of namespaces) {
    const en = flatten(JSON.parse(readFileSync(join(dir, 'en', `${ns}.json`), 'utf8')))
    for (const locale of LOCALES.slice(1)) {
      const tr = flatten(JSON.parse(readFileSync(join(dir, locale, `${ns}.json`), 'utf8')))
      for (const key of Object.keys(en)) {
        if (!(key in tr)) {
          console.log(`missing   ${locale}  ${ns}.${key}`)
          problems++
        } else if (args(en[key]) !== args(tr[key])) {
          console.log(`args      ${locale}  ${ns}.${key}  en={${args(en[key])}} ${locale}={${args(tr[key])}}`)
          problems++
        }
      }
      for (const key of Object.keys(tr)) {
        if (!(key in en)) {
          console.log(`extra     ${locale}  ${ns}.${key}`)
          problems++
        }
      }
    }
  }
  console.log(problems ? `\n${problems} problem(s).` : 'All translations complete.')
  process.exit(problems ? 1 : 0)
}
console.log(`Synced ${namespaces.length} namespaces for ${LOCALES.length} locales.`)
